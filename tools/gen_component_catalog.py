#!/usr/bin/env python3
"""Regenerate docs/COMPONENTS.md from the sources.

Lists every public top-level ``@Composable`` function whose name starts with an
upper-case letter, grouped by module and package. Run after an upstream sync:

    python -I tools/gen_component_catalog.py
    python -I tools/gen_component_catalog.py --gallery-coverage
"""

from __future__ import annotations

import argparse
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# (module, source root, package prefix that is stripped from the group heading)
MODULES = [
    ("coui-patterns", "src/main/kotlin", "io.github.tianli0.coui17.patterns"),
    ("coui-ui", "src/commonMain/kotlin", "io.github.suqi8.coui.kmp"),
    ("coui-preference", "src/commonMain/kotlin", "io.github.suqi8.coui.kmp"),
]

GROUP_TITLES = {
    "": "Patterns",
    "basic": "Components",
    "window": "Dialogs, sheets and popups in their own window",
    "overlay": "Dialogs, sheets and popups drawn inside the page",
    "layout": "Dialog and sheet layouts",
    "preference": "Preference rows",
    "menu": "Dropdown menus",
    "popup": "Dropdown popups",
    "theme": "Theme",
}

SKIP_GROUPS = ("kit", "utils", "anim", "icon", "interfaces", "color", "effect", "preference.internal")

COMPOSABLE = re.compile(
    r"@Composable\s*(?:@[\w.]+(?:\([^)]*\))?\s*)*(?:(public|internal|private)\s+)?(?:inline\s+)?fun\s+(?:<[^>]+>\s+)?(?:[\w.]+\.)?([A-Z]\w*)\s*\(",
)
MODIFIER = re.compile(
    r"@Composable\s*(?:(public|internal|private)\s+)?fun\s+Modifier\.(\w+)\s*\(",
)
KOTLIN_IMPORT = re.compile(r"^import ([\w.]+)(?: as (\w+))?$", re.M)


def gallery_calls() -> dict[str, set[str]]:
    calls: dict[str, set[str]] = defaultdict(set)
    for file in sorted((ROOT / "gallery/src/main/kotlin").rglob("*.kt")):
        text = file.read_text(encoding="utf-8")
        for match in KOTLIN_IMPORT.finditer(text):
            qualified, alias = match.groups()
            name = alias or qualified.rsplit(".", 1)[-1]
            if re.search(rf"\b{re.escape(name)}\s*[(\x7b]", text[match.end():]):
                calls[qualified].add(file.name)
    return calls


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--gallery-coverage",
        action="store_true",
        help="List direct Gallery call sites and catalog entries without one, without rewriting the Markdown.",
    )
    args = parser.parse_args()
    calls = gallery_calls() if args.gallery_coverage else {}
    matched = 0
    out = [
        "# Component catalog",
        "",
        "Generated by `tools/gen_component_catalog.py` from the sources; do not edit by hand.",
        "Every public composable is listed with the file that defines it. Signatures and KDoc live",
        "in the source, and the `gallery` app shows the common ones in use.",
        "",
    ]
    total = 0
    for module, src, prefix in MODULES:
        groups: dict[str, dict[str, set[str]]] = defaultdict(lambda: defaultdict(set))
        base = ROOT / module / src
        for file in sorted(base.rglob("*.kt")):
            text = file.read_text(encoding="utf-8")
            package = re.search(r"^package\s+([\w.]+)", text, re.M)
            if not package:
                continue
            group = package.group(1)[len(prefix):].lstrip(".")
            if group.startswith(SKIP_GROUPS):
                continue
            names: set[str] = set()
            for match in COMPOSABLE.finditer(text):
                if match.group(1) in ("internal", "private"):
                    continue
                names.add(match.group(2))
            for match in MODIFIER.finditer(text):
                if match.group(1) in ("internal", "private"):
                    continue
                names.add("Modifier." + match.group(2))
            if names:
                groups[group][file.stem] |= names
                if args.gallery_coverage:
                    for name in sorted(names):
                        targets = calls.get(f"{package.group(1)}.{name.removeprefix('Modifier.')}", ())
                        matched += bool(targets)
                        where = ", ".join(sorted(targets)) if targets else "-"
                        print(f"{module}/{file.stem}.kt\t{name}\t{where}")
        if not groups:
            continue
        count = sum(len(n) for files in groups.values() for n in files.values())
        total += count
        out += [f"## `{module}`", ""]
        for group in sorted(groups, key=lambda g: (g != "", g != "basic", g)):
            title = GROUP_TITLES.get(group, group)
            out += [f"### {title}", "", "| File | Composables |", "| :--- | :--- |"]
            for stem in sorted(groups[group]):
                names = ", ".join(f"`{n}`" for n in sorted(groups[group][stem]))
                out.append(f"| `{stem}.kt` | {names} |")
            out.append("")
    if args.gallery_coverage:
        print(f"Direct Gallery calls: {matched}/{total} catalog entries (source scan)")
        return
    out += [
        "## Foundation modules",
        "",
        "| Module | Entry points |",
        "| :--- | :--- |",
        "| `coui-blur` | `rememberLayerBackdrop`, `Modifier.layerBackdrop`, `LocalBackdrop`, `LocalBlurEnabled`, `isBlurEnabled`, `isRuntimeShaderSupported`, `progressiveTextureBlur`, `BlurDefaults` |",
        "| `coui-squircle` | `SquircleShape`, squircle background and border modifiers, `LocalSquircleEnabled` |",
        "| `coui-icons` | `COUIIcons.*` in `io.github.suqi8.coui.kmp.icon.extended` |",
        "| `coui-shader`, `coui-core` | RuntimeShader / RenderEffect wrappers, `ExperimentalCOUIApi`, platform utilities |",
        "",
    ]
    out.insert(5, f"{total} public composables in the three component modules.")
    (ROOT / "docs" / "COMPONENTS.md").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"docs/COMPONENTS.md: {total} composables")


if __name__ == "__main__":
    main()
